def test_upload_with_deflated_bundle(tmp_path: Path, prefix: Path, home: Path) -> None:
    upload = B.write(tmp_path / "Contoso_1.2.3.0.msixupload",
                     B.make_upload([("Contoso.msixbundle", B.standard_bundle()),
                                    ("Contoso.appxsym", b"symbols" * 100)]))
    assert msix.classify(upload) == "upload"
    info = msix.inspect(upload)
    assert info.kind == "upload"
    assert info.selected_package == "Contoso.msixbundle/Contoso_x64.msix"
    assert info.arch == "x64" and info.status == "partial"
    cache = home / ".cache" / "lindos" / "msix"
    assert not cache.exists() or not any(cache.iterdir())      # scratch copy cleaned up
    inst = msix.install(upload, prefix)
    assert inst.apps[0][1].read_bytes() == B.exe("x64 editor")
    assert not [p for p in _windowsapps(prefix).iterdir() if p.name.startswith(".lindos")]


def test_upload_with_packages_picks_x64(tmp_path: Path) -> None:
    upload = B.write(tmp_path / "Contoso.appxupload",
                     B.make_upload([("Contoso_x86.appx", X86), ("Contoso_x64.appx", X64), ("Contoso_arm64.appx", ARM64)],
                                   compress=zipfile.ZIP_STORED))
    info = msix.inspect(upload)
    assert info.selected_package == "Contoso_x64.appx" and info.arch == "x64"


def test_upload_with_only_arm_packages(tmp_path: Path) -> None:
    upload = B.write(tmp_path / "Contoso.msixupload", B.make_upload([("Contoso_arm64.msix", ARM64)]))
    info = msix.inspect(upload)
    assert info.status == "unsupported" and "ARM" in info.reason


def test_upload_recurses_only_once(tmp_path: Path) -> None:
    inner_upload = B.make_upload([("Contoso.msixbundle", B.standard_bundle())])
    upload = B.write(tmp_path / "nested.msixupload", B.make_upload([("Inner.msixupload", inner_upload),
                                                                     ("Trick.msix", inner_upload)]))
    assert msix.classify(upload) == "upload"
    with pytest.raises(msix.MsixError, match="no usable app package"):
        msix.inspect(upload)


def test_flat_bundle_inside_upload_is_refused(tmp_path: Path) -> None:
    flat = B.make_bundle([Inner("Contoso_x64.msix", X64, embed=False, offset=None)])
    upload = B.write(tmp_path / "flat.msixupload", B.make_upload([("Contoso.msixbundle", flat),
                                                                   ("Contoso_x64.msix", X64)]))
    with pytest.raises(msix.MsixError, match="flat bundle"):
        msix.inspect(upload)


def test_upload_respects_max_bytes(tmp_path: Path, prefix: Path) -> None:
    upload = B.write(tmp_path / "Contoso.msixupload", B.make_upload([("Contoso.msixbundle", B.standard_bundle())]))
    with pytest.raises(msix.MsixError, match="limit|no usable"):
        msix.install(upload, prefix, max_bytes=1000)

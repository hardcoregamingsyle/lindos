@pytest.mark.parametrize("inner, words", [
    (Inner("Contoso_x64.msix", B.arch_package("x64", version="1.2.3.1")), "version 1.2.3.1"),
    (Inner("Contoso_x64.msix", X86), "built for x86"),
    (Inner("Contoso_x64.msix", B.arch_package("x64", name="Fabrikam.Other")), "different app"),
    (Inner("Contoso_x64.msix", B.arch_package("x64", publisher="CN=Mallory")), "different publisher"),
    (Inner("Contoso_x64.msix", X64, compress=zipfile.ZIP_DEFLATED), "compressed"),
    (Inner("Contoso_x64.msix", X64, offset=12345), "position"),
    (Inner("Contoso_x64.msix", X64, size=99), "size"),
    (Inner("Contoso_x64.msix", X64, embed=False, offset=4096), "isn't"),
    # Offset="0" is a real (falsy-but-present) declared offset, not "no Offset attribute" -- a
    # manifest claiming the package is embedded at byte 0 while it is absent from the bundle's own
    # zip must still be treated as damaged, not silently fall through to flat-sibling lookup
    # (sec-compat:F2).
    (Inner("Contoso_x64.msix", X64, embed=False, offset=0), "isn't"),
    (Inner("Contoso_x64.msix", B.standard_bundle()), "AppxManifest.xml"),   # bundle inside a bundle
])
def test_inner_package_checks(tmp_path: Path, inner, words: str, prefix: Path) -> None:
    path = _bundle(tmp_path, [inner])
    with pytest.raises(msix.MsixError, match=words):
        msix.inspect(path)
    with pytest.raises(msix.MsixError):
        msix.install(path, prefix)
    assert not _windowsapps(prefix).exists() or not any(_windowsapps(prefix).iterdir())


def test_bundle_manifest_errors(tmp_path: Path) -> None:
    dup = _bundle(tmp_path, [Inner("Contoso_x64.msix", X64), Inner("contoso_X64.msix", X64)], fname="dup.msixbundle")
    with pytest.raises(msix.MsixError, match="twice"):
        msix.inspect(dup)
    bad_name = _bundle(tmp_path, [Inner("Contoso_x64.exe", X64)], fname="bad.msixbundle")
    with pytest.raises(msix.MsixError, match="FileName"):
        msix.inspect(bad_name)
    unknown_ns = _bundle(tmp_path, [Inner("Contoso_x64.msix", X64)], fname="ns.msixbundle",
                         root_ns="http://example.invalid/bundle")
    with pytest.raises(msix.MsixError, match="schema"):
        msix.inspect(unknown_ns)



"""msix.py: bundles (selection, identity checks, stored-entry rules), flat bundles and upload files.

Fixtures are generated by test_msix_builders.py (never vendored).  Hermetic: tmp dirs only, no Wine.
"""
from __future__ import annotations

import importlib.util
import os
import sys
import zipfile
from pathlib import Path

import pytest

from lindos_compat import msix


def _builders():
    name = "lindos_test_msix_builders"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name("test_msix_builders.py"))
        mod = importlib.util.module_from_spec(spec)
        sys.modules[name] = mod
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return sys.modules[name]


B = _builders()
Inner = B.Inner
PID = msix.publisher_id(B.PUBLISHER)
X64 = B.arch_package("x64")
X86 = B.arch_package("x86")
ARM64 = B.arch_package("arm64")


@pytest.fixture(autouse=True)
def _sandbox(home: Path) -> Path:
    return home


@pytest.fixture()
def prefix(tmp_path: Path) -> Path:
    return tmp_path / "prefixes" / f"{B.NAME}_{PID}"


def _bundle(tmp_path: Path, inners, fname: str = "Contoso.msixbundle", **kw) -> Path:
    return B.write(tmp_path / "dl" / fname, B.make_bundle(inners, **kw))


def _windowsapps(prefix: Path) -> Path:
    return prefix / "drive_c" / "Program Files" / "WindowsApps"



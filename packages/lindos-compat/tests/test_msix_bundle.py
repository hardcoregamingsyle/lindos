# (d) flat bundles: the package is a sibling file
# --------------------------------------------------------------------------- #
def _flat(tmp_path: Path, file_name: str, *, sibling: str = "Contoso_x64.msix", data: bytes = X64,
          size="auto") -> Path:
    folder = tmp_path / "flat"
    folder.mkdir(parents=True, exist_ok=True)
    if sibling:
        B.write(folder / sibling, data)
    inner = Inner(file_name, X64, embed=False, offset=None, size=size)
    return B.write(folder / "Contoso.appxbundle", B.make_bundle([inner], root_ns=B.NS_B2017, schema="3.0"))


def test_flat_bundle_uses_the_sibling_file(tmp_path: Path, prefix: Path) -> None:
    path = _flat(tmp_path, "Contoso_x64.msix")
    assert msix.classify(path) == "bundle"
    info = msix.inspect(path)
    assert info.selected_package == "Contoso_x64.msix" and info.status == "partial"
    inst = msix.install(path, prefix)
    assert inst.apps[0][1].read_bytes() == B.exe("x64 editor")


def test_flat_bundle_sibling_lookup_is_case_insensitive(tmp_path: Path) -> None:
    path = _flat(tmp_path, "CONTOSO_X64.MSIX")
    assert msix.inspect(path).selected_package == "CONTOSO_X64.MSIX"


@pytest.mark.parametrize("file_name, words", [
    ("../Contoso_x64.msix", "outside its own folder"),
    ("sub/Contoso_x64.msix", "outside its own folder"),
    ("..\\Contoso_x64.msix", "outside its own folder"),
    ("http://example.invalid/Contoso_x64.msix", "network or the web"),
    ("https://example.invalid/Contoso_x64.msix", "network or the web"),
    ("\\\\fileserver\\share\\Contoso_x64.msix", "network or the web"),
    ("file:Contoso_x64.msix", "network or the web"),
])
def test_flat_bundle_never_leaves_its_folder(tmp_path: Path, file_name: str, words: str) -> None:
    B.write(tmp_path / "Contoso_x64.msix", X64)          # a tempting target one level up
    path = _flat(tmp_path, file_name)
    with pytest.raises(msix.MsixError, match=words):
        msix.inspect(path)


def test_flat_bundle_missing_sibling(tmp_path: Path) -> None:
    path = _flat(tmp_path, "Contoso_x64.msix", sibling="")
    with pytest.raises(msix.MsixError, match="were not downloaded"):
        msix.inspect(path)


def test_flat_bundle_size_mismatch(tmp_path: Path) -> None:
    path = _flat(tmp_path, "Contoso_x64.msix", size=len(X64) + 1)
    with pytest.raises(msix.MsixError, match="different size"):
        msix.inspect(path)


def test_flat_bundle_refuses_symlinked_sibling(tmp_path: Path) -> None:
    real = B.write(tmp_path / "elsewhere" / "Contoso_x64.msix", X64)
    path = _flat(tmp_path, "Contoso_x64.msix", sibling="")
    try:
        os.symlink(real, path.parent / "Contoso_x64.msix")
    except (OSError, NotImplementedError):
        pytest.skip("symbolic links are not available here")
    with pytest.raises(msix.MsixError, match="not a regular file"):
        msix.inspect(path)



def test_stub_packages_are_skipped(tmp_path: Path) -> None:
    path = _bundle(tmp_path, [Inner("Contoso_x64.msix", X64, b5_stub=True), Inner("Contoso_x86.msix", X86, arch="x86",
                                                                                  b5_stub=False)])
    assert msix.inspect(path).selected_package == "Contoso_x86.msix"
    only_stub = _bundle(tmp_path, [Inner("Contoso_x64.msix", X64, b5_stub=True)], fname="stub.msixbundle")
    with pytest.raises(msix.MsixError, match="stub"):
        msix.inspect(only_stub)


def test_arm_only_bundle_is_explained(tmp_path: Path, prefix: Path) -> None:
    path = _bundle(tmp_path, [Inner("Contoso_arm64.msix", ARM64, arch="arm64"),
                              Inner("Contoso_arm.msix", B.arch_package("arm"), arch="arm"),
                              Inner("Contoso_x86a64.msix", B.arch_package("x86a64"), arch="x86a64")])
    info = msix.inspect(path)
    assert info.status == "unsupported" and "ARM" in info.reason
    assert "arm, arm64, x86a64" in info.reason
    assert info.package_full_name == f"{B.NAME}_{B.BUNDLE_VERSION}_neutral_~_{PID}"
    with pytest.raises(msix.MsixError, match="ARM"):
        msix.install(path, prefix)


def test_neutral_beats_x86_and_desktop_family_breaks_ties(tmp_path: Path) -> None:
    neutral_xbox = B.arch_package("neutral", exe_tag="xbox")
    neutral_desktop = B.arch_package("neutral", exe_tag="desktop")

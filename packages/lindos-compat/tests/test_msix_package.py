def test_psf_launcher_is_resolved_to_the_real_program(tmp_path: Path, prefix: Path) -> None:
    config = {"applications": [{"id": "app", "executable": "%MsixPackageRoot%\\VFS/ProgramFilesX64/Contoso App/"
                                                           "Contoso [Beta].exe",
                                "arguments": '--from-psf "a b"', "workingDirectory": "",
                                "startScript": {"scriptPath": "setup.ps1", "runInVirtualEnvironment": True}}],
              "processes": [{"executable": ".*", "fixups": [{"dll": "FileRedirectionFixup64.dll"}]}]}
    inst = msix.install(_psf_package(tmp_path, config), prefix)
    [(app, exe_path, _)] = inst.apps

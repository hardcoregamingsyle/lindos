def test_install_refuses_symlink_in_the_c_drive(pkg: Path, prefix: Path, tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (prefix / "drive_c" / "Program Files").mkdir(parents=True)
    try:
        os.symlink(outside, prefix / "drive_c" / "Program Files" / "Contoso App", target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("symbolic links are not available here")
    with pytest.raises(msix.MsixError, match="symbolic link"):
        msix.install(pkg, prefix)
    assert list(outside.iterdir()) == []
    assert not (_windowsapps(prefix) / FULL).exists()


def test_launch_info_expands_macros_and_splits_arguments(tmp_path: Path, prefix: Path) -> None:
    attrs = (B.CLASSIC + ' uap11:Parameters="--root &quot;$(package.effectivePath)&quot; $(env:ProgramData) '
             '$(env:USERNAME) $$5" uap11:CurrentDirectoryPath="$(package.installedPath)\\Assets" '
             'desktop4:Subsystem="console"')
    path = _pkg(tmp_path, man=B.manifest(apps=[B.app_xml(attrs=attrs)]))
    inst = msix.install(path, prefix)
    info = msix.launch_info(inst, 0)
    root = msix.package_root_windows(inst.info)
    assert root == "C:\\Program Files\\WindowsApps\\" + FULL
    assert info["args"] == ["--root", root, "C:\\ProgramData", "%USERNAME%", "$5"]
    assert Path(str(info["cwd"])) == inst.install_dir / "Assets"
    assert info["console"] is True and info["list_entry"] is True
    assert info["aumid"] == f"{B.NAME}_{PID}!App" and info["pfn"] == f"{B.NAME}_{PID}"
    assert info["source"] == "msix"
    assert info["exe"] == str(prefix / "drive_c" / "Program Files" / "Contoso App" / "Contoso [Beta].exe")


def test_launch_info_defaults_to_exe_folder(pkg: Path, prefix: Path) -> None:
    inst = msix.install(pkg, prefix)

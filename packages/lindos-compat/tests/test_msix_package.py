def test_inspect_packaged_classic_app(pkg: Path) -> None:
    info = msix.inspect(pkg)
    assert info.kind == "package"
    assert (info.name, info.publisher, info.version, info.arch, info.resource_id) == (
        B.NAME, B.PUBLISHER, B.VERSION, "x64", "")
    assert info.publisher_id == PID
    assert info.package_full_name == FULL
    assert info.package_family_name == f"{B.NAME}_{PID}"
    assert info.display_name == "Contoso Photo Editor"
    assert info.publisher_display == "Contoso Ltd"
    assert info.status == "partial" and "usually works" in info.reason
    assert info.signed and not info.unsigned_marker and info.store_signals == []
    assert not info.framework and not info.resource_package and info.selected_package is None
    [app] = info.apps
    assert app.app_class == "win32"
    assert app.executable == B.EXE_REL
    assert app.list_entry and not app.console
    assert app.logo == "Assets/Square44x44Logo.targetsize-256_altform-unplated.png"
